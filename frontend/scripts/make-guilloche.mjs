// Writes src/assets/guilloche.svg: a seamless guilloché tile (interfering sine
// bands, like the security print on Tunisian bus tickets and recharge cards).
// Authored vector, regenerate with: node scripts/make-guilloche.mjs
import { writeFileSync } from 'node:fs'

const W = 240, H = 96, STEP = 2
const paths = []
for (let k = 0; k < 9; k++) {
  for (const sign of [1, -1]) {
    let d = ''
    for (let x = 0; x <= W; x += STEP) {
      // two waves whose periods divide the tile width, so the tile repeats seamlessly
      const y = H / 2
        + sign * (18 + k * 2.2) * Math.sin((2 * Math.PI * x) / W * 2 + k * 0.35)
        + 6 * Math.sin((2 * Math.PI * x) / W * 6 + k * 0.7)
      d += `${x === 0 ? 'M' : 'L'}${x},${y.toFixed(2)}`
    }
    paths.push(`<path d="${d}"/>`)
  }
}
const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}" viewBox="0 0 ${W} ${H}">
<!-- DressMe guilloché tile. Provenance: authored vector, generated by frontend/scripts/make-guilloche.mjs -->
<g fill="none" stroke="#1E2E8E" stroke-width="0.5" stroke-opacity="0.08">${paths.join('')}</g>
</svg>
`
writeFileSync(new URL('../src/assets/guilloche.svg', import.meta.url), svg)
console.log('wrote src/assets/guilloche.svg', svg.length, 'bytes')
